// Writes supabase/seed.sql from the demo data, so the database and the app's demo mode never disagree.
// Run: npm run seed:gen
import { writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DEMO_AREAS, DEMO_OPERATOR } from '../src/demoData';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const out: string[] = [];

out.push('-- GENERATED by `npm run seed:gen` from packages/shared/src/demoData.ts. Do not edit by hand.');
out.push('-- Demo operator, areas and illustrative CAD rates for Toronto. Safe to run more than once.');
out.push('');
out.push(
  `insert into operator (id, name, country, timezone, currency, service_fee_bps) values (${q(DEMO_OPERATOR.id)}, ${q(
    DEMO_OPERATOR.name,
  )}, ${q(DEMO_OPERATOR.country)}, ${q(DEMO_OPERATOR.timezone)}, ${q(DEMO_OPERATOR.currency)}, ${DEMO_OPERATOR.service_fee_bps}) on conflict (id) do nothing;`,
);
out.push('');

for (const a of DEMO_AREAS) {
  const parent = a.level === 3 ? DEMO_AREAS.find((x) => x.level === 2)?.id : undefined;
  out.push(`-- ${a.name}`);
  out.push(
    `insert into parking_area (id, operator_id, parent_id, level, kind, name, geom, max_stay_minutes) values (${q(a.id)}, ${q(
      a.operator_id,
    )}, ${parent ? q(parent) : 'null'}, ${a.level}, ${q(a.level === 2 ? 'region' : 'zone')}, ${q(a.name)}, st_multi(st_setsrid(st_geomfromgeojson(${q(
      JSON.stringify(a.geometry),
    )}), 4326)), ${a.max_stay_minutes ?? 'null'}) on conflict (id) do nothing;`,
  );
  out.push(
    `insert into rate_plan (id, operator_id, area_id, name, currency, min_charge_cents, daily_max_cents, grace_minutes) values (${q(a.plan.id)}, ${q(
      a.operator_id,
    )}, ${q(a.id)}, ${q(a.plan.name)}, ${q(a.plan.currency)}, ${a.plan.min_charge_cents}, ${a.plan.daily_max_cents ?? 'null'}, ${a.plan.grace_minutes}) on conflict (id) do nothing;`,
  );
  out.push(`delete from rate_rule where rate_plan_id = ${q(a.plan.id)};`);
  a.plan.rules.forEach((r) => {
    out.push(
      `insert into rate_rule (rate_plan_id, days_of_week, start_time, end_time, price_per_hour_cents, priority) values (${q(a.plan.id)}, array[${r.days_of_week.join(
        ',',
      )}]::smallint[], ${q(r.start_time)}, ${q(r.end_time)}, ${r.price_per_hour_cents}, ${r.priority});`,
    );
  });
  out.push('');
}

out.push('-- After you sign up in the app, make yourself staff (run in the Supabase SQL editor):');
out.push(`--   select dev_set_role('you@example.com', 'operator_admin', ${q(DEMO_OPERATOR.id)});  -- console + officer powers`);
out.push(`--   select dev_set_role('officer@example.com', 'officer', ${q(DEMO_OPERATOR.id)});    -- officer mode in the app`);

const here = dirname(fileURLToPath(import.meta.url));
writeFileSync(resolve(here, '../../../supabase/seed.sql'), out.join('\n') + '\n');
console.log('wrote supabase/seed.sql');
